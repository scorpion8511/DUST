"""Compute transferability baselines for single- and multi-modal embeddings.

This script consolidates several transferability metrics from the literature so
they can be evaluated on top of the feature files produced by the extraction
pipelines in this repository. Both single-modality (image only) checkpoints
generated by :mod:`extract_features.py` and multimodal CLIP-style checkpoints
produced by :mod:`multimodal_feature_extraction.py` are supported.

Metrics implemented
-------------------
* Gaussian Bhattacharyya Coefficient (GBC)
* Self-Distilled Fisher Discriminant Analysis (SFDA)
* TransRate
* EMMS (requires text backbones from Hugging Face)
* NCTI
* H-score

The implementation is largely adapted from the reference repositories linked in
``README.md`` and the snippet provided by the user. Minor adjustments were made
to integrate the metrics with PyTorch ``.pth`` feature dumps and to improve
numerical stability.

Example usage
-------------
Compute all metrics for a single-modality checkpoint::

    python transferability_baselines.py         single /path/to/features.pth         --manifest /path/to/manifest.csv --label-column subtype

Evaluate a multimodal feature file across all magnifications::

    python transferability_baselines.py         multi /path/to/multimodal_features.pth         --manifest /path/to/manifest.csv         --label-column subtype

Results are printed to stdout and can optionally be exported as JSON via
``--json``.
"""

