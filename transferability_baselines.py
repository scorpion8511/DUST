def _load_manifest(manifest: Optional[str]) -> Optional[pd.DataFrame]:
    if manifest is None:
        return None
    if not os.path.exists(manifest):
        raise FileNotFoundError(f"Manifest not found: {manifest}")
    return pd.read_csv(manifest)


def _build_label_map(labels: Sequence[str]) -> Tuple[np.ndarray, Dict[int, str]]:
    mapping: Dict[str, int] = {}
    numeric: List[int] = []
    for label in labels:
        key = str(label)
        if key not in mapping:
            mapping[key] = len(mapping)
        numeric.append(mapping[key])
    reverse = {idx: lab for lab, idx in mapping.items()}
    return np.asarray(numeric, dtype=np.int64), reverse


def load_single_features(path: str, manifest: Optional[str], label_column: Optional[str]) -> FeatureBundle:
    payload: MutableMapping[str, object] = torch.load(path, map_location="cpu")
    if "embeddings" not in payload:
        raise KeyError("Expected 'embeddings' in feature file")
    embeddings = _to_numpy(payload["embeddings"])
    labels_tensor = payload.get("labels")
    labels: Optional[np.ndarray]
    label_names: Optional[Dict[int, str]] = None

    manifest_df = _load_manifest(manifest)
    if labels_tensor is not None and isinstance(labels_tensor, torch.Tensor) and labels_tensor.numel() == embeddings.shape[0]:
        labels = labels_tensor.detach().cpu().numpy().astype(np.int64)
        if manifest_df is not None and label_column and "row_indices" in payload:
            indices = np.asarray(payload["row_indices"], dtype=np.int64)
            subset = manifest_df.iloc[indices]
            label_series = subset[label_column].astype(str).tolist()
            numeric, reverse = _build_label_map(label_series)
            if numeric.shape[0] == labels.shape[0]:
                labels = numeric
                label_names = reverse
    elif manifest_df is not None and label_column:
        if "row_indices" not in payload:
            raise ValueError("Feature file is missing 'row_indices'; provide labels directly or regenerate features")
        indices = np.asarray(payload["row_indices"], dtype=np.int64)
        subset = manifest_df.iloc[indices]
        numeric, reverse = _build_label_map(subset[label_column].astype(str))
        labels = numeric
        label_names = reverse
    else:
        labels = None

    return FeatureBundle(embeddings=embeddings, labels=labels, label_names=label_names, metadata=payload)


def load_multimodal_features(
    path: str,
    manifest: Optional[str],
    *,
    label_column: Optional[str],
    region_column: str,
    magnification_column: str,
) -> Tuple[Dict[int, FeatureBundle], FeatureBundle]:
    payload: MutableMapping[str, object] = torch.load(path, map_location="cpu")
    if "image_embeddings" not in payload or "text_embeddings" not in payload:
        raise KeyError("Expected 'image_embeddings' and 'text_embeddings' in multimodal feature file")

    image_embeddings: Dict[int, torch.Tensor] = {}
    for key, value in payload["image_embeddings"].items():
        image_embeddings[int(key)] = value
    magnifications = sorted(image_embeddings.keys())

    metadata = payload.get("metadata", {})
    region_ids: List[str] = list(metadata.get("region_ids", []))
    csv_mapping: Dict[str, Sequence[str]] = metadata.get("csv_region_mapping", {})

    manifest_df = _load_manifest(manifest)
    labels: Optional[np.ndarray] = None
    label_names: Optional[Dict[int, str]] = None
    if manifest_df is not None and label_column:
        lookup: Dict[str, str] = {}
        for _, row in manifest_df.iterrows():
            lookup[str(row[region_column])] = str(row[label_column])
        resolved: List[str] = []
        for region in region_ids:
            candidates = csv_mapping.get(region, [region])
            label = None
            for candidate in candidates:
                if candidate in lookup:
                    label = lookup[candidate]
                    break
            if label is None:
                warnings.warn(f"Unable to resolve label for region '{region}' from manifest; assigning placeholder")
                label = "unknown"
            resolved.append(label)
        labels, label_names = _build_label_map(resolved)

    bundles: Dict[int, FeatureBundle] = {}
    for mag in magnifications:
        embeddings = _to_numpy(image_embeddings[mag])
        bundles[mag] = FeatureBundle(embeddings=embeddings, labels=labels, label_names=label_names, metadata=metadata)

    text_bundle = FeatureBundle(
        embeddings=_to_numpy(payload["text_embeddings"]),
        labels=labels,
        label_names=label_names,
        metadata=metadata,
    )
    return bundles, text_bundle


