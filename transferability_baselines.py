def evaluate_metrics(bundle: FeatureBundle, metrics: Sequence[str], *, gaussian_type: str, emms_backend: Optional[str], emms_model: Optional[str]) -> Dict[str, object]:
    if bundle.embeddings.size == 0:
        raise ValueError("No embeddings found in the feature file")
    labels = bundle.labels
    results: Dict[str, object] = {}

    feature_matrix = bundle.embeddings.astype(np.float64)
    label_array = labels.astype(np.int64) if labels is not None else None

    for metric in metrics:
        if metric == "gbc":
            if label_array is None:
                warnings.warn("Skipping GBC because labels are unavailable")
                continue
            results["gbc"] = gbc_score(feature_matrix, label_array, gaussian_type=gaussian_type)
        elif metric == "sfda":
            if label_array is None:
                warnings.warn("Skipping SFDA because labels are unavailable")
                continue
            results["sfda"] = sfda_score(feature_matrix, label_array)
        elif metric == "transrate":
            if label_array is None:
                warnings.warn("Skipping TransRate because labels are unavailable")
                continue
            results["transrate"] = transrate_score(feature_matrix, label_array)
        elif metric == "emms":
            if bundle.label_names is None:
                warnings.warn("Skipping EMMS because label names are unavailable")
                continue
            embeddings = _resolve_label_embeddings(bundle.label_names, backend=emms_backend, model_name=emms_model)
            results["emms"] = emms_score(feature_matrix, embeddings)
        elif metric == "ncti":
            if label_array is None:
                warnings.warn("Skipping NCTI because labels are unavailable")
                continue
            seli, ncc, vc = ncti_score(feature_matrix, label_array)
            results["ncti_seli"] = seli
            results["ncti_ncc"] = ncc
            results["ncti_vc"] = vc
        elif metric == "hscore":
            if label_array is None:
                warnings.warn("Skipping H-score because labels are unavailable")
                continue
            results["h_score"] = h_score(feature_matrix, label_array)
        else:
            raise ValueError(f"Unknown metric '{metric}'")
    return {key: float(value) for key, value in results.items()}


def _aggregate_metric_dict(outputs: Mapping[str, Mapping[str, float]]) -> Dict[str, float]:
    totals: Dict[str, float] = {}
    counts: Dict[str, int] = {}
    for metric_dict in outputs.values():
        for metric, value in metric_dict.items():
            totals[metric] = totals.get(metric, 0.0) + float(value)
            counts[metric] = counts.get(metric, 0) + 1
    return {metric: totals[metric] / counts[metric] for metric in totals if counts[metric] > 0}


def _kendall_tau_per_metric(metric_scores: Mapping[str, Mapping[str, float]], ground_truth: Mapping[str, float]) -> Dict[str, float]:
    tau_results: Dict[str, float] = {}
    for metric, scores in metric_scores.items():
        common_models = sorted(set(scores) & set(ground_truth))
        if len(common_models) < 2:
            tau_results[metric] = float("nan")
            continue
        predicted = np.array([scores[model] for model in common_models], dtype=np.float64)
        reference = np.array([ground_truth[model] for model in common_models], dtype=np.float64)
        tau, _ = weightedtau(predicted, reference)
        tau_results[metric] = float(tau)
    return tau_results


def evaluate_single_dataset(
    dataset: str,
    metrics: Sequence[str],
    *,
    gaussian_type: str,
    emms_backend: Optional[str],
    emms_model: Optional[str],
) -> Dict[str, object]:
    if dataset not in DEFAULT_SINGLE_DATASET_MODEL_PATHS:
        raise ValueError(f"Unknown dataset '{dataset}' for single-modality evaluation")
    models = DEFAULT_SINGLE_DATASET_MODEL_PATHS[dataset]
    ground_truth = DEFAULT_SINGLE_GROUND_TRUTH.get(dataset, {})

    raw_results: Dict[str, Dict[str, float]] = {}
    metric_scores: Dict[str, Dict[str, float]] = {}

    for model_name, config in models.items():
        manifest = None
        label_column = "subtype"
        if "msci" in config and isinstance(config["msci"], Mapping):
            manifest = config["msci"].get("manifest")
            label_column = config["msci"].get("label_column", label_column)

        bundle = load_single_features(config["eval"], manifest, label_column)
        model_results = evaluate_metrics(
            bundle,
            metrics,
            gaussian_type=gaussian_type,
            emms_backend=emms_backend,
            emms_model=emms_model,
        )
        raw_results[model_name] = model_results
        _print_results(f"{dataset} :: {model_name}", model_results)

        for metric_name, value in model_results.items():
            metric_scores.setdefault(metric_name, {})[model_name] = float(value)

    tau_scores = _kendall_tau_per_metric(metric_scores, ground_truth)

    if tau_scores:
        print(f"\nKendall tau against ground truth ({dataset}):")
        for metric_name, tau in tau_scores.items():
            print(f"  {metric_name}: {tau}")

    return {
        "models": raw_results,
        "tau": tau_scores,
        "ground_truth": ground_truth,
    }


def evaluate_multimodal_dataset(
    dataset: str,
    metrics: Sequence[str],
    *,
    gaussian_type: str,
    emms_backend: Optional[str],
    emms_model: Optional[str],
    manifest: Optional[str] = None,
    label_column: str = "subtype",
    region_column: str = "patch_id",
    magnification_column: str = "patch_scale",
) -> Dict[str, object]:
    if dataset not in DEFAULT_DATASET_MODEL_PATHS:
        raise ValueError(f"Unknown dataset '{dataset}' for multimodal evaluation")
    models = DEFAULT_DATASET_MODEL_PATHS[dataset]
    ground_truth = DEFAULT_GROUND_TRUTH.get(dataset, {})

    raw_outputs: Dict[str, Dict[str, Dict[str, float]]] = {}
    aggregated_scores: Dict[str, Dict[str, float]] = {}
    metric_scores: Dict[str, Dict[str, float]] = {}

    for model_name, feature_path in models.items():
        image_bundles, text_bundle = load_multimodal_features(
            feature_path,
            manifest,
            label_column=label_column,
            region_column=region_column,
            magnification_column=magnification_column,
        )

        per_outputs: Dict[str, Dict[str, float]] = {}
        for magnification, bundle in image_bundles.items():
            key = f"image_{magnification}x"
            per_outputs[key] = evaluate_metrics(
                bundle,
                metrics,
                gaussian_type=gaussian_type,
                emms_backend=emms_backend,
                emms_model=emms_model,
            )
            _print_results(f"{dataset} :: {model_name} [{key}]", per_outputs[key])

        per_outputs["text"] = evaluate_metrics(
            text_bundle,
            metrics,
            gaussian_type=gaussian_type,
            emms_backend=emms_backend,
            emms_model=emms_model,
        )
        _print_results(f"{dataset} :: {model_name} [text]", per_outputs["text"])

        raw_outputs[model_name] = per_outputs
        aggregated = _aggregate_metric_dict(per_outputs)
        aggregated_scores[model_name] = aggregated
        print(f"\nAggregated metrics for {dataset} :: {model_name}:")
        for metric_name, value in aggregated.items():
            print(f"  {metric_name}: {value}")

        for metric_name, value in aggregated.items():
            metric_scores.setdefault(metric_name, {})[model_name] = float(value)

    tau_scores = _kendall_tau_per_metric(metric_scores, ground_truth)

    if tau_scores:
        print(f"\nKendall tau against ground truth ({dataset}):")
        for metric_name, tau in tau_scores.items():
            print(f"  {metric_name}: {tau}")

    return {
        "models": raw_outputs,
        "aggregated": aggregated_scores,
        "tau": tau_scores,
        "ground_truth": ground_truth,
    }


def _resolve_label_embeddings(label_names: Mapping[int, str], *, backend: Optional[str], model_name: Optional[str]) -> np.ndarray:
    labels = [label_names[idx] for idx in sorted(label_names)]
    backend = backend or "clip"
    if backend == "clip":
        from transformers import CLIPModel, CLIPProcessor

        model_name = model_name or "laion/CLIP-ViT-g-14-laion2B-s12B-b42K"
        model = CLIPModel.from_pretrained(model_name)
        processor = CLIPProcessor.from_pretrained(model_name)
        inputs = processor(text=labels, padding=True, return_tensors="pt")
        with torch.inference_mode():
            text_features = model.get_text_features(**inputs)
        return text_features.cpu().numpy()
    if backend == "gpt2":
        from transformers import GPT2Model, GPT2Tokenizer

        model_name = model_name or "gpt2-medium"
        tokenizer = GPT2Tokenizer.from_pretrained(model_name)
        tokenizer.pad_token = tokenizer.eos_token
        model = GPT2Model.from_pretrained(model_name)
        encoded = tokenizer(labels, return_tensors="pt", padding=True, truncation=True)
        with torch.inference_mode():
            outputs = model(**encoded)
        return outputs.last_hidden_state.mean(dim=1).cpu().numpy()
    if backend == "bert":
        from transformers import AutoTokenizer, BertModel

        model_name = model_name or "bert-large-uncased"
        tokenizer = AutoTokenizer.from_pretrained(model_name)
        model = BertModel.from_pretrained(model_name)
        encoded = tokenizer(labels, return_tensors="pt", padding=True, truncation=True)
        with torch.inference_mode():
            outputs = model(**encoded)
        return outputs.last_hidden_state.mean(dim=1).cpu().numpy()
    raise ValueError(f"Unsupported EMMS backend '{backend}'")


