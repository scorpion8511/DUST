def compute_bhattacharyya_distance(mu1: np.ndarray, mu2: np.ndarray, sigma1: np.ndarray, sigma2: np.ndarray) -> float:
    """Compute the Bhattacharyya distance between diagonal Gaussians."""

    avg_sigma = (sigma1 + sigma2) / 2.0
    first = np.sum((mu1 - mu2) ** 2 / avg_sigma) / 8.0
    second = np.sum(np.log(avg_sigma)) - 0.5 * (np.sum(np.log(sigma1)) + np.sum(np.log(sigma2)))
    return float(first + 0.5 * second)


def _per_class_stats(features: np.ndarray, labels: np.ndarray, spherical: bool) -> Dict[int, Dict[str, np.ndarray]]:
    stats: Dict[int, Dict[str, np.ndarray]] = {}
    for label in np.unique(labels):
        mask = labels == label
        feats = features[mask]
        mean = feats.mean(axis=0)
        var = np.maximum(feats.var(axis=0), 1e-4)
        if spherical:
            var = np.full_like(var, var.mean())
        stats[int(label)] = {"mean": mean, "var": var}
    return stats


def gbc_score(features: np.ndarray, labels: np.ndarray, gaussian_type: str = "diagonal") -> float:
    if gaussian_type not in {"diagonal", "spherical"}:
        raise ValueError("gaussian_type must be either 'diagonal' or 'spherical'")
    stats = _per_class_stats(features, labels, spherical=gaussian_type == "spherical")
    accum: List[float] = []
    for c1 in np.unique(labels):
        distances: List[float] = []
        for c2 in np.unique(labels):
            if c1 == c2:
                continue
            dist = compute_bhattacharyya_distance(
                stats[int(c1)]["mean"],
                stats[int(c2)]["mean"],
                stats[int(c1)]["var"],
                stats[int(c2)]["var"],
            )
            distances.append(math.exp(-dist))
        accum.append(np.sum(distances))
    return float(-np.sum(accum))


def _covariance(X: np.ndarray, shrinkage: float = -1.0) -> np.ndarray:
    emp = np.cov(np.asarray(X).T, bias=True)
    if shrinkage < 0:
        return emp
    n_features = emp.shape[0]
    mu = np.trace(emp) / n_features
    shrunk = (1.0 - shrinkage) * emp
    shrunk.flat[:: n_features + 1] += shrinkage * mu
    return shrunk


def _softmax(logits: np.ndarray) -> np.ndarray:
    shifted = logits - logits.max(axis=1, keepdims=True)
    exp = np.exp(shifted)
    return exp / exp.sum(axis=1, keepdims=True)


def _class_means(X: np.ndarray, y: np.ndarray) -> Tuple[np.ndarray, np.ndarray]:
    classes, inv = np.unique(y, return_inverse=True)
    counts = np.bincount(inv)
    means = np.zeros((len(classes), X.shape[1]), dtype=X.dtype)
    np.add.at(means, inv, X)
    means /= counts[:, None]
    outer = np.zeros_like(means)
    for idx in range(len(classes)):
        outer[idx] = (np.sum(means, axis=0) - means[idx]) / max(1, len(classes) - 1)
    return means, outer


def _iterative_max_eigenvalue(matrix: np.ndarray, max_iterations: int = 5) -> float:
    rng = np.random.default_rng(42)
    vec = rng.standard_normal(matrix.shape[0])
    value = 0.0
    for _ in range(max_iterations):
        vec = matrix @ vec
        norm = np.linalg.norm(vec)
        if norm == 0:
            break
        vec /= norm
        value = float(vec @ (matrix @ vec))
    return value


class SFDA:
    def __init__(self, shrinkage: Optional[float] = None, priors: Optional[np.ndarray] = None, n_components: Optional[int] = None) -> None:
        self.shrinkage = shrinkage
        self.priors = priors
        self.n_components = n_components
        self.scalings_: Optional[np.ndarray] = None
        self.coef_: Optional[np.ndarray] = None
        self.intercept_: Optional[np.ndarray] = None
        self.means_: Optional[np.ndarray] = None
        self.priors_: Optional[np.ndarray] = None
        self.covariance_: Optional[np.ndarray] = None

    def _solve(self, X: np.ndarray, y: np.ndarray) -> None:
        classes, inv = np.unique(y, return_inverse=True)
        counts = np.bincount(inv)
        means = np.zeros((len(classes), X.shape[1]), dtype=X.dtype)
        np.add.at(means, inv, X)
        means /= counts[:, None]
        self.means_ = means

        cov = np.zeros((X.shape[1], X.shape[1]), dtype=X.dtype)
        for idx, cls in enumerate(classes):
            samples = X[y == cls]
            cov += self.priors_[idx] * _covariance(samples)
        self.covariance_ = cov

        Sw = cov
        if self.shrinkage is None:
            largest = _iterative_max_eigenvalue(Sw, max_iterations=5)
            shrinkage = max(math.exp(-5.0 * largest), 1e-10)
            self.shrinkage = shrinkage
        else:
            shrinkage = self.shrinkage

        St = _covariance(X, shrinkage=self.shrinkage)
        n_features = Sw.shape[0]
        mu = np.trace(Sw) / n_features
        shrunk = (1.0 - shrinkage) * Sw
        shrunk.flat[:: n_features + 1] += shrinkage * mu
        Sb = St - shrunk

        evals, evecs = np.linalg.eigh(np.linalg.pinv(shrunk) @ Sb)
        order = np.argsort(evals)[::-1]
        evecs = evecs[:, order]
        self.scalings_ = evecs
        self.coef_ = means @ evecs @ evecs.T
        self.intercept_ = -0.5 * np.diag(self.means_ @ self.coef_.T) + np.log(self.priors_)

    def fit(self, X: np.ndarray, y: np.ndarray) -> "SFDA":
        classes = np.unique(y)
        max_components = min(len(classes) - 1, X.shape[1])
        if self.n_components is not None and self.n_components > max_components:
            raise ValueError("n_components cannot exceed min(n_features, n_classes - 1)")
        self._max_components = max_components if self.n_components is None else self.n_components
        _, inv = np.unique(y, return_inverse=True)
        self.priors_ = np.bincount(inv) / len(y)
        self._solve(X, y)
        return self

    def transform(self, X: np.ndarray) -> np.ndarray:
        if self.scalings_ is None:
            raise RuntimeError("Model must be fit before calling transform")
        return (X @ self.scalings_)[:, : self._max_components]

    def predict_proba(self, X: np.ndarray) -> np.ndarray:
        if self.coef_ is None or self.intercept_ is None:
            raise RuntimeError("Model must be fit before calling predict_proba")
        scores = X @ self.coef_.T + self.intercept_
        return _softmax(scores)


def sfda_score(X: np.ndarray, y: np.ndarray) -> float:
    X = X.copy()
    model = SFDA()
    probs = model.fit(X, y).predict_proba(X)
    probs = _softmax(np.log(np.clip(probs, 1e-12, 1.0)))
    means, outer = _class_means(X, y)
    num_classes = len(np.unique(y))
    for cls in range(num_classes):
        idx = np.where(y == cls)[0]
        cls_prob = probs[idx, cls][:, None]
        X[idx] = cls_prob * X[idx] + (1.0 - cls_prob) * outer[cls]
    second = SFDA(shrinkage=model.shrinkage)
    probs = second.fit(X, y).predict_proba(X)
    indices = np.arange(len(y))
    score = np.sum(probs[indices, y]) / len(y)
    return float(score)


def coding_rate(Z: np.ndarray, eps: float = 1e-4) -> float:
    n, d = Z.shape
    identity = np.eye(d)
    _, rate = np.linalg.slogdet(identity + (1.0 / (n * eps)) * (Z.T @ Z))
    return 0.5 * rate


def transrate_score(Z: np.ndarray, y: np.ndarray, eps: float = 1e-4) -> float:
    Z = Z - Z.mean(axis=0, keepdims=True)
    total = coding_rate(Z, eps)
    per_class = 0.0
    for cls in np.unique(y):
        cls_feats = Z[y == cls]
        per_class += coding_rate(cls_feats, eps)
    return float(total - per_class / len(np.unique(y)))


def sparsemax(z: np.ndarray) -> np.ndarray:
    z_sorted = np.sort(z, axis=1)[:, ::-1]
    z_cumsum = np.cumsum(z_sorted, axis=1)
    k = np.arange(1, z.shape[1] + 1)
    z_check = 1 + k * z_sorted > z_cumsum
    k_z = z.shape[1] - np.argmax(z_check[:, ::-1], axis=1)
    tau_sum = z_cumsum[np.arange(z.shape[0]), k_z - 1]
    tau = ((tau_sum - 1) / k_z).reshape(-1, 1)
    return np.maximum(0.0, z - tau)


def emms_score(Z: np.ndarray, label_embeddings: np.ndarray) -> float:
    if label_embeddings.ndim != 2:
        raise ValueError("label_embeddings must be 2-D [num_labels, embed_dim]")
    num_labels, embed_dim = label_embeddings.shape
    N = Z.shape[0]
    expanded = np.repeat(label_embeddings[None, :, :], N, axis=0)
    expanded = np.transpose(expanded, (0, 2, 1))  # [N, embed_dim, num_labels]
    X = Z.copy()
    Y = expanded.copy()

    for i in range(num_labels):
        y_mean = Y[:, :, i].mean(axis=0)
        y_std = Y[:, :, i].std(axis=0)
        Y[:, :, i] = (Y[:, :, i] - y_mean) / (y_std + 1e-8)
    X = (X - X.mean(axis=0, keepdims=True)) / (X.std(axis=0, keepdims=True) + 1e-8)

    lam = np.full((num_labels, 1), 1.0 / num_labels)
    b = (Y @ lam).reshape(N, embed_dim)
    w, _, _, _ = np.linalg.lstsq(X, b, rcond=None)
    for _ in range(1):
        a = Y.reshape(N * embed_dim, num_labels)
        target = (X @ w).reshape(N * embed_dim)
        lam = np.linalg.lstsq(a, target, rcond=None)[0].reshape(1, num_labels)
        lam = sparsemax(lam)
        lam = lam.reshape(num_labels, 1)
        b = (Y @ lam).reshape(N, embed_dim)
    prediction = X @ w
    residual = np.sum((prediction - b) ** 2) / (N * embed_dim)
    return float(-residual)


def ncti_score(X: np.ndarray, y: np.ndarray) -> Tuple[float, float, float]:
    from sklearn.decomposition import PCA
    from sklearn.discriminant_analysis import LinearDiscriminantAnalysis

    C = len(np.unique(y))
    pca = PCA(n_components=min(64, X.shape[1]))
    X_pca = pca.fit_transform(X)
    shrink = max(math.exp(-pca.explained_variance_[:32].sum()), 1e-10)
    if shrink == 1e-10:
        lda = LinearDiscriminantAnalysis(solver="svd")
    else:
        lda = LinearDiscriminantAnalysis(solver="eigen", shrinkage=float(shrink))
    low = lda.fit_transform(X_pca, y)
    low -= low.mean(axis=0, keepdims=True)
    seli = np.linalg.norm(low, ord="nuc")
    probs = lda.predict_proba(X_pca)
    ncc = float(np.sum(probs[np.arange(X.shape[0]), y]) / X.shape[0])
    vc = 0.0
    for cls in np.unique(y):
        cls_probs = probs[y == cls]
        vc += np.linalg.norm(cls_probs, ord="nuc")
    vc = math.log(vc)
    return float(seli), float(ncc), float(vc)


def h_score(X: np.ndarray, y: np.ndarray) -> float:
    def cov(mat: np.ndarray) -> np.ndarray:
        centered = mat - mat.mean(axis=0, keepdims=True)
        return centered.T @ centered / max(1, mat.shape[0] - 1)

    cov_x = cov(X)
    classes = np.unique(y)
    g = np.zeros_like(X)
    for cls in classes:
        mean = X[y == cls].mean(axis=0)
        g[y == cls] = mean
    cov_g = cov(g)
    score = np.trace(np.linalg.pinv(cov_x, rcond=1e-12) @ cov_g)
    return float(score)


